import 'dart:convert';
import 'dart:typed_data';
import 'dart:ui';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:seizure_app/core/dtos/result_dto.dart';
import 'package:seizure_app/core/dtos/seizure_log_dto.dart';
import 'package:seizure_app/core/dtos/user_dto.dart';
import 'package:share_plus/share_plus.dart';

class SeizureReportService {
  const SeizureReportService();

  Future<ResultDto<void>> shareClinicalReport({
    required UserDto? user,
    required List<SeizureLogDto> logs,
    Rect? sharePositionOrigin,
  }) async {
    try {
      final String date = _date(DateTime.now());
      final Uint8List csv = Uint8List.fromList(utf8.encode(_buildCsv(logs)));
      final Uint8List pdf = await _buildPdf(user, logs);
      await SharePlus.instance.share(
        ShareParams(
          subject: 'Seizure record $date',
          text:
              'Personal seizure record generated by Seizure Alert. Review it with a healthcare professional.',
          files: <XFile>[
            XFile.fromData(csv, mimeType: 'text/csv'),
            XFile.fromData(pdf, mimeType: 'application/pdf'),
          ],
          fileNameOverrides: <String>[
            'seizure-record-$date.csv',
            'seizure-record-$date.pdf',
          ],
          sharePositionOrigin: sharePositionOrigin,
        ),
      );
      return ResultDto.success(null);
    } catch (_) {
      return ResultDto.failure('The report could not be prepared.');
    }
  }

  String _buildCsv(List<SeizureLogDto> logs) {
    final List<List<Object?>> rows = <List<Object?>>[
      <Object?>[
        'Date and time',
        'Duration seconds',
        'Seizure type',
        'Severity',
        'Awareness',
        'Aura or warning signs',
        'Trigger',
        'Location',
        'Recovery minutes',
        'Rescue medication used',
        'Injuries or complications',
        'Notes',
        'Emergency alert sent',
      ],
      for (final SeizureLogDto log in logs)
        <Object?>[
          log.occurredAt.toIso8601String(),
          log.durationSeconds,
          log.seizureType,
          log.severity,
          log.awareness,
          log.aura,
          log.trigger,
          log.location,
          log.recoveryMinutes,
          log.rescueMedicationUsed ? 'Yes' : 'No',
          log.injuries,
          log.notes,
          log.alertFired ? 'Yes' : 'No',
        ],
    ];
    return rows
        .map((List<Object?> row) => row.map(_csvCell).join(','))
        .join('\r\n');
  }

  Future<Uint8List> _buildPdf(UserDto? user, List<SeizureLogDto> logs) async {
    final pw.Document document = pw.Document();
    final int totalSeconds = logs.fold<int>(
      0,
      (int value, SeizureLogDto log) => value + (log.durationSeconds ?? 0),
    );
    final Map<String, int> triggerCounts = <String, int>{};
    for (final SeizureLogDto log in logs) {
      final String? trigger = log.trigger?.trim();
      if (trigger != null && trigger.isNotEmpty) {
        triggerCounts.update(
          trigger,
          (int count) => count + 1,
          ifAbsent: () => 1,
        );
      }
    }
    final List<MapEntry<String, int>> triggers = triggerCounts.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(36),
        header: (pw.Context context) => pw.Container(
          padding: const pw.EdgeInsets.only(bottom: 12),
          decoration: const pw.BoxDecoration(
            border: pw.Border(bottom: pw.BorderSide(color: PdfColors.grey400)),
          ),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: <pw.Widget>[
              pw.Text(
                'SEIZURE RECORD',
                style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
              ),
              pw.Text(_date(DateTime.now())),
            ],
          ),
        ),
        build: (pw.Context context) => <pw.Widget>[
          pw.SizedBox(height: 20),
          pw.Text(
            user?.displayName?.trim().isNotEmpty == true
                ? user!.displayName!.trim()
                : 'Personal health record',
            style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 6),
          pw.Text(
            'This user-entered record supports a clinical conversation. It is not a diagnosis.',
            style: const pw.TextStyle(color: PdfColors.grey700),
          ),
          pw.SizedBox(height: 20),
          pw.Row(
            children: <pw.Widget>[
              _summaryBox('Recorded events', '${logs.length}'),
              pw.SizedBox(width: 10),
              _summaryBox(
                'Average duration',
                logs.isEmpty ? '—' : _duration(totalSeconds ~/ logs.length),
              ),
              pw.SizedBox(width: 10),
              _summaryBox(
                'Latest event',
                logs.isEmpty ? '—' : _date(logs.first.occurredAt),
              ),
            ],
          ),
          if (triggers.isNotEmpty) ...<pw.Widget>[
            pw.SizedBox(height: 22),
            pw.Text(
              'Most recorded triggers',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 6),
            pw.Text(
              triggers
                  .take(5)
                  .map(
                    (MapEntry<String, int> entry) =>
                        '${entry.key} (${entry.value})',
                  )
                  .join(' • '),
            ),
          ],
          pw.SizedBox(height: 24),
          pw.Text(
            'Events',
            style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 8),
          for (final SeizureLogDto log in logs)
            pw.Container(
              margin: const pw.EdgeInsets.only(bottom: 8),
              padding: const pw.EdgeInsets.all(10),
              decoration: pw.BoxDecoration(
                border: pw.Border.all(color: PdfColors.grey400),
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
              ),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: <pw.Widget>[
                  pw.Text(
                    '${_dateTime(log.occurredAt)}  •  ${log.seizureType ?? 'Type not recorded'}',
                    style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                  ),
                  pw.SizedBox(height: 4),
                  pw.Text(_eventSummary(log)),
                  if (log.notes?.trim().isNotEmpty == true) ...<pw.Widget>[
                    pw.SizedBox(height: 4),
                    pw.Text(log.notes!.trim()),
                  ],
                ],
              ),
            ),
          if (logs.isEmpty) pw.Text('No seizure events have been recorded.'),
        ],
      ),
    );
    return document.save();
  }

  pw.Widget _summaryBox(String label, String value) => pw.Expanded(
    child: pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: const pw.BoxDecoration(
        color: PdfColors.grey100,
        borderRadius: pw.BorderRadius.all(pw.Radius.circular(6)),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: <pw.Widget>[
          pw.Text(label, style: const pw.TextStyle(color: PdfColors.grey700)),
          pw.SizedBox(height: 4),
          pw.Text(value, style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        ],
      ),
    ),
  );

  String _eventSummary(SeizureLogDto log) {
    final List<String> details = <String>[
      if (log.durationSeconds != null) _duration(log.durationSeconds!),
      if (log.severity != null) log.severity!,
      if (log.awareness != null) 'Awareness: ${log.awareness}',
      if (log.trigger != null) 'Trigger: ${log.trigger}',
      if (log.recoveryMinutes != null)
        'Recovery: ${log.recoveryMinutes} minutes',
      if (log.rescueMedicationUsed) 'Rescue medication used',
      if (log.injuries != null) 'Injuries: ${log.injuries}',
    ];
    return details.isEmpty
        ? 'No clinical details recorded'
        : details.join(' • ');
  }

  String _csvCell(Object? value) {
    final String text = value?.toString() ?? '';
    return '"${text.replaceAll('"', '""')}"';
  }

  String _duration(int seconds) {
    final int minutes = seconds ~/ 60;
    final int remainder = seconds % 60;
    if (minutes == 0) return '$remainder seconds';
    if (remainder == 0) return '$minutes minutes';
    return '$minutes minutes $remainder seconds';
  }

  String _date(DateTime date) =>
      '${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}';

  String _dateTime(DateTime date) =>
      '${_date(date)} ${date.hour.toString().padLeft(2, '0')}:${date.minute.toString().padLeft(2, '0')}';
}
